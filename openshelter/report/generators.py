"""Report generators: JSON, Markdown and self-contained HTML briefs.

HTML output is a single file with inline CSS — printable to PDF from any
browser, embeddable in municipal portals, and diff-able in git for audit
trails (a requirement for public-funding accountability).
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

from ..core.engine import DesignBrief


def to_json(brief: DesignBrief) -> str:
    d = {
        "schema": "openshelter.brief/0.1",
        "site": brief.site.to_dict(),
        "code": asdict(brief.code),
        "structural_system": brief.structural_system,
        "strategies": {
            "energy": brief.energy_strategy,
            "water": brief.water_strategy,
            "sanitation": brief.sanitation_strategy,
            "thermal": brief.thermal_strategy,
        },
        "recommendations": [asdict(r) for r in brief.recommendations],
        "compliance_checks": brief.compliance_checks,
    }
    return json.dumps(d, indent=2, ensure_ascii=False)


_CSS = """
body{font-family:system-ui,Segoe UI,Arial,sans-serif;margin:2rem auto;max-width:860px;color:#222;line-height:1.45}
h1{border-bottom:3px solid #0b7285;padding-bottom:.3rem} h2{color:#0b7285;margin-top:1.6rem}
table{border-collapse:collapse;width:100%} td,th{border:1px solid #ccc;padding:.4rem .6rem;text-align:left;font-size:.92rem}
.pass{color:#186a3b;font-weight:bold}.fail{color:#a4041c;font-weight:bold}
.p1{background:#ffe3e3}.badge{display:inline-block;border-radius:4px;padding:0 .4rem;font-size:.8rem;background:#e7f5ff}
footer{margin-top:2rem;font-size:.8rem;color:#666;border-top:1px solid #ccc;padding-top:.6rem}
"""


def to_markdown(brief: DesignBrief) -> str:
    s = brief.site
    lines = [
        f"# OpenShelter design brief — {s.lat:.2f}, {s.lon:.2f}",
        "",
        f"**Code profile:** {brief.code.name} (`{brief.code.id}`)",
        f"**Structural system:** {brief.structural_system}",
        f"**Strategies:** energy={brief.energy_strategy}; water={brief.water_strategy}; "
        f"sanitation={brief.sanitation_strategy}; thermal={brief.thermal_strategy}",
        "",
        "## Hazard fingerprint",
        "| hazard | susceptibility |", "|---|---|",
    ]
    for h, v in sorted(s.hazards.items()):
        lines.append(f"| {h} | {v:.2f} |")
    lines += ["", "## Recommendations (priority order)", ""]
    for i, r in enumerate(brief.recommendations, 1):
        lines.append(f"{i}. **[{r.topic}]** {r.measure}  ")
        lines.append(f"   _Why:_ {r.reason}  _(priority P{r.priority}, cost band: {r.cost_band})_")
    lines += ["", "## Compliance checks", "", "| check | status | detail |", "|---|---|---|"]
    for c in brief.compliance_checks:
        status = "PASS" if c["passed"] else "REVIEW"
        lines.append(f"| {c['check']} | {status} | {c['detail']} |")
    lines += ["", "---", "_Generated by OpenShelter. Deterministic preview tool — "
              "a licensed local engineer must sign structural calculations._"]
    return "\n".join(lines)


def to_html(brief: DesignBrief) -> str:
    rows = "".join(
        f"<tr class='{'p1' if r.priority == 1 else ''}'><td>{r.topic}</td>"
        f"<td>{r.measure}</td><td>{r.reason}</td><td>P{r.priority}</td><td>{r.cost_band}</td></tr>"
        for r in brief.recommendations
    )
    checks = "".join(
        f"<tr><td>{c['check']}</td>"
        f"<td class='{'pass' if c['passed'] else 'fail'}'>"
        f"{'PASS' if c['passed'] else 'NEEDS REVIEW'}</td><td>{c['detail']}</td></tr>"
        for c in brief.compliance_checks
    )
    hazards = "".join(f"<span class='badge'>{k}: {v:.2f}</span> " for k, v in sorted(brief.site.hazards.items()))
    s = brief.site
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>OpenShelter brief {s.lat:.2f},{s.lon:.2f}</title><style>{_CSS}</style></head><body>
<h1>Resilient shelter design brief</h1>
<p><strong>Site:</strong> {s.lat:.4f}, {s.lon:.4f} · elev {s.elevation_m} m ·
soil {s.soil_bearing_kpa} kPa · serving ~{s.population_served:,} people</p>
<p><strong>Code profile:</strong> {brief.code.name} <code>{brief.code.id}</code></p>
<p><strong>Structural system:</strong> {brief.structural_system}</p>
<h2>Hazard fingerprint</h2><p>{hazards}</p>
<h2>Recommendations</h2>
<table><tr><th>Topic</th><th>Measure</th><th>Reason (data + code citation)</th><th>P</th><th>Cost</th></tr>{rows}</table>
<h2>Compliance checks</h2>
<table><tr><th>Check</th><th>Status</th><th>Detail</th></tr>{checks}</table>
<footer>Schema openshelter.brief/0.1 · deterministic output · verify inputs against authoritative
national datasets before procurement. Generated by OpenShelter (AGPL-3.0).</footer>
</body></html>"""


def write_outputs(brief: DesignBrief, outdir: Path, stem: str = "brief") -> dict:
    outdir.mkdir(parents=True, exist_ok=True)
    paths = {
        "json": outdir / f"{stem}.json",
        "md": outdir / f"{stem}.md",
        "html": outdir / f"{stem}.html",
    }
    paths["json"].write_text(to_json(brief), encoding="utf-8")
    paths["md"].write_text(to_markdown(brief), encoding="utf-8")
    paths["html"].write_text(to_html(brief), encoding="utf-8")
    return paths
